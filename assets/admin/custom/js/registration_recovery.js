jQuery(function ($) {
    'use strict';
    $(document).on('click', '[data-send-registration-email]', function (event) {
        event.preventDefault();
        var $button = $(this), $form = $button.closest('.admin-registration-email-action'), $status = $form.find('[data-registration-email-status]');
        if ($button.prop('disabled')) return;
        $button.prop('disabled', true).attr('aria-busy', 'true');
        $status.removeClass('text-danger text-success').text('Sending registration email…');
        $.ajax({
            url: $form.data('url'), type: 'POST',
            data: { q2r_secure: $('#csrf_hash').val() || $('input[name="q2r_secure"]').first().val() }, dataType: 'json',
            success: function (result) {
                if (result.csrf_hash) {
                    if (typeof updateGlobalCsrfHash === 'function') updateGlobalCsrfHash(result.csrf_hash);
                    // Admin forms use the shared CSRF field generated by form_open.
                    $('input[name="q2r_secure"]').val(result.csrf_hash);
                    $('#csrf_hash').val(result.csrf_hash);
                }
                $status.addClass(result.status ? 'text-success' : 'text-danger').text(result.msg || 'The request could not be completed.');
                if (result.status && result.sent_at) $('[data-registration-last-sent]').text('Last registration email: ' + result.sent_at);
            },
            error: function () { $status.addClass('text-danger').text('The request could not be confirmed. Check Activity History before retrying.'); },
            complete: function () { $button.prop('disabled', false).removeAttr('aria-busy'); }
        });
    });
});
